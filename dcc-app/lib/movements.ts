export function getMovement(day: number): Movement | undefined {
  return movements.find((m) => m.day === day);
}

export function getPartProgress(completedDays: number[]) {
  const parts = [1, 2, 3, 4];
  return parts.map((p) => {
    const daysInPart = movements.filter((m) => m.part === p);
    const done = daysInPart.filter((m) => completedDays.includes(m.day)).length;
    return { part: p, partName: daysInPart[0]?.partName ?? '', total: daysInPart.length, done };
  });
}
